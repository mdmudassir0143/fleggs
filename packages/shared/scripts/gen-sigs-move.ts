// Writes move/flurry/tests/test_sigs.move: referee signatures for the fixed test profile so Move
// tests can exercise training::earn and daily::submit. Usage: tsx scripts/gen-sigs-move.ts
import { writeFileSync } from 'node:fs';
import { Ed25519Keypair } from '@mysten/sui/keypairs/ed25519';
import { toHex } from '@mysten/sui/utils';
import { signAttestation } from '../src/attestation';

const kp = Ed25519Keypair.fromSecretKey(new Uint8Array(32).fill(7));
const PROFILE = '0xdba72804cc9504a82bbaa13ed4a83a0e2c6219d7e45125cf57fd10cbab957a97';
export const SCORE = 500, SNOW = 10n, EXPIRES = 1_800_000_000_000n;
const lines: string[] = [];
for (const purpose of [1, 2]) for (let game = 0; game < 4; game++) for (let nonce = 0; nonce <= 8; nonce++) {
  const { signature } = await signAttestation({ profileId: PROFILE, nonce: BigInt(nonce), purpose, game, score: SCORE, snowflakes: SNOW, expiresMs: EXPIRES }, kp);
  lines.push(`    if (purpose == ${purpose} && game == ${game} && nonce == ${nonce}) return x"${toHex(signature)}";`);
}
writeFileSync(new URL('../../../move/flurry/tests/test_sigs.move', import.meta.url), `// Generated by packages/shared/scripts/gen-sigs-move.ts — do not edit.
#[test_only]
module flurry::test_sigs;

/// Referee signature (test key 0x07×32) for the hatch_tests player's profile, score ${SCORE}, ${SNOW} Snowflakes.
public fun sig(purpose: u8, game: u8, nonce: u64): vector<u8> {
${lines.join('\n')}
    abort 999
}
`);
console.log('wrote', lines.length, 'signatures');
